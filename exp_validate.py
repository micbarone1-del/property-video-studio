"""exp_validate.py - VALIDATION BATCH of the clip acceptance standard v0 (2026-11-05). EXPERIMENT TOOL, NOT PRODUCTION.
Fresh scenes (never tested before), balanced over the room categories, ONE 360p draft per scene with the production prompt (R0, eye-level director). Every clip goes through
clip_standard.evaluate (the SAME code as the shadow mode in production). Michele watches a BLIND shuffled list: all clips the standard rejects + a random sample of the ones it passes.
  python3 exp_validate.py run [--n 90] [--jobs j1,j2] [--sample 15] [--budget 9.0] [--go]    without --go: scene count, clip cost and a Claude estimate, spends nothing
  python3 exp_validate.py score RUN_ID LABELS.json      LABELS.json = {"bad": [codes], "part": [codes], "ok": [codes]} for the clips he watched
  python3 exp_validate.py reveal RUN_ID                 FREE: standard verdict, reasons and numbers per code
Environment: PVS_JOBS_DIR = drafts (test instance /var/www/pvs_test_jobs), PVS_VOLUME_SCRATCH = where the videos go (production scratch).
The budget covers 360p clips (0.06 USD) AND the judge calls (measured, see the report); the spend file is cumulative, so the cap handed to the guard is spent + budget.
"""
import json
import random
import string
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import exp_facade as ef
import exp_volume as ev

JUDGE_USD_ESTIMATE = 0.04      # per clip, PROVISIONAL (6 images + ~400 output tokens on Sonnet); the run prints the measured value
PER_VIDEO = 6                  # clips per review video


def used_cases() -> set:
    """job:scene of every clip already generated by any earlier round (their key_*.json)."""
    out = set()
    for p in ef.OUT.glob("key_*.json"):
        try:
            for k in json.loads(p.read_text()):
                out.add(str(k.get("case")))
        except Exception:
            pass
    return out


def pick_fresh(job_ids, n, used) -> list:
    """[(job, scene, cat)] round-robin over the categories, never a scene already used."""
    by = {}
    for job, i, cat in ef.pick_scenes(job_ids, 10 ** 6):
        if f"{job}:{i}" not in used:
            by.setdefault(cat, []).append((job, i, cat))
    for v in by.values():
        random.shuffle(v)
    out = []
    while len(out) < n and any(by.values()):
        for cat in sorted(by):
            if by[cat] and len(out) < n:
                out.append(by[cat].pop())
    return out


def review_set(rows, sample, rng=random) -> list:
    """rows with a standard verdict -> (codes to watch shuffled, rejected codes, sampled passes). Every reject is watched; passes are sampled."""
    rej = [r["code"] for r in rows if r.get("standard") == "reject"]
    pas = [r["code"] for r in rows if r.get("standard") == "pass"]
    pick = rng.sample(pas, min(sample, len(pas)))
    watch = rej + pick
    rng.shuffle(watch)
    return watch, rej, pick


def score(rows, labels) -> dict:
    """Numbers for the decision. labels: code -> bad|part|ok (only the clips he watched). Misses are ESTIMATED from the random sample of passes."""
    lab = {r["code"]: labels.get(r["code"]) for r in rows}
    rej = [r for r in rows if r.get("standard") == "reject" and lab[r["code"]]]
    pas = [r for r in rows if r.get("standard") == "pass" and lab[r["code"]]]
    all_pass = [r for r in rows if r.get("standard") == "pass"]
    rb = sum(1 for r in rej if lab[r["code"]] == "bad")
    rp = sum(1 for r in rej if lab[r["code"]] == "part")
    ro = sum(1 for r in rej if lab[r["code"]] == "ok")
    pb = sum(1 for r in pas if lab[r["code"]] == "bad")
    miss_rate = pb / len(pas) if pas else None
    est_missed = round(miss_rate * len(all_pass), 1) if miss_rate is not None else None
    caught = rb / (rb + est_missed) if (est_missed is not None and rb + est_missed) else None
    ok_total = ro + (len(all_pass) - (est_missed or 0))
    return {"clips": len(rows), "rejected": sum(1 for r in rows if r.get("standard") == "reject"), "watched_rejects": len(rej), "reject_bad": rb, "reject_part": rp, "reject_ok": ro,
            "watched_passes": len(pas), "pass_bad": pb, "est_bad_in_passes": est_missed, "est_bad_caught": round(caught, 2) if caught is not None else None,
            "est_false_reject_rate": round(ro / ok_total, 3) if ok_total > 0 else None}


def main(argv) -> int:
    def opt(name, default):
        return argv[argv.index(name) + 1] if name in argv else default
    n = int(opt("--n", "90"))
    sample = int(opt("--sample", "15"))
    budget = float(opt("--budget", "9.0"))
    go = "--go" in argv
    ef.OUT.mkdir(parents=True, exist_ok=True)
    jobs = [j for j in opt("--jobs", "").split(",") if j] or sorted(p.name for p in ev.JOBS_DIR.iterdir() if (p / "job_meta.json").is_file())
    scenes = pick_fresh(jobs, n, used_cases())
    cats = {}
    for _, _, c in scenes:
        cats[c] = cats.get(c, 0) + 1
    est = len(scenes) * (ev.CLIP_USD + JUDGE_USD_ESTIMATE)
    ev.say(f"{len(scenes)} fresh scene(s) from {len(jobs)} draft(s): {cats}")
    ev.say(f"about {len(scenes)} x ({ev.CLIP_USD} clip + {JUDGE_USD_ESTIMATE} judge, provisional) = {est:.2f} USD (budget {budget})")
    if est > budget:
        ev.say("estimate exceeds the budget: refusing"); return 1
    if not go:
        ev.say("Nothing done (no --go)."); return 0
    from dotenv import load_dotenv
    load_dotenv(ev.HERE / ".env")
    import clip_standard as cs
    import exp_prompt_ab as ab
    ev.OUT = ef.OUT; ev.SPEND = ef.OUT / "spend.json"
    cap = ev.spent() + budget
    ev.say(f"spent so far {ev.spent():.2f} -> cap {cap:.2f}")
    cases = []
    for job, i, cat in scenes:
        with ef._env(PVS_DIRECTOR_EYE="1"):
            p, plan, img = ef.capture_prompt(job, i)
        if p:
            cases.append({"job": job, "scene": i, "cat": cat, "img": str(img), "prompt": p, "plan": plan})
        else:
            ev.say(f"{job}:{i} no production prompt captured: skipped")
    run_id = time.strftime("%m%d_%H%M%S")
    run_dir = ef.OUT / run_id; run_dir.mkdir(parents=True, exist_ok=True)
    codes = set()

    def newcode():
        while True:
            c = "".join(random.choice(string.ascii_lowercase) for _ in range(3))
            if c not in codes:
                codes.add(c); return c
    coded = [(newcode(), c) for c in cases]
    judge_usd = {"in": 0.0}

    def one(t):
        cd, c = t
        row = {"code": cd, "case": f"{c['job']}:{c['scene']}", "cat": c["cat"], "plan": c["plan"], "prompt": c["prompt"], "ok": False}
        if ev.spent() + ev.CLIP_USD > cap:
            row["why"] = "cap"; return row
        ev.add_spend(ev.CLIP_USD, f"validate {row['case']}")
        out = run_dir / f"{cd}.mp4"
        row["ok"] = bool(ab.generate_luma(Path(c["img"]), c["prompt"], out) and out.exists())
        if row["ok"]:
            u = {"input_tokens": 0, "output_tokens": 0, "calls": 0, "cost_eur": 0.0}
            r = cs.evaluate(out, usage_out=u)
            row.update(standard=r["standard_verdict"], reasons=r["reasons"], geo=r["geo"], judge=r["judge"], error=r["error"], judge_cost_eur=u.get("cost_eur"))
        ev.say(f"{row['case']} {cd} {'ok' if row['ok'] else 'FAILED'} {row.get('standard')}")
        return row
    with ThreadPoolExecutor(max_workers=3) as ex:
        rows = list(ex.map(one, coded))
    (ef.OUT / f"validate_{run_id}.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1))
    done = [r for r in rows if r.get("standard")]
    cost = sum(r.get("judge_cost_eur") or 0 for r in done)
    ev.say(f"judge cost measured: {cost:.2f} EUR for {len(done)} clips = {cost / max(1, len(done)):.3f} EUR per clip")
    watch, rej, pick = review_set(done, sample)
    ev.say(f"{len(done)} clips judged | standard rejects {len(rej)} | passes {len(done) - len(rej)} (sampled {len(pick)}) | to watch: {len(watch)} in blind order")
    for k in range(0, len(watch), PER_VIDEO):
        chunk = watch[k:k + PER_VIDEO]
        parts = []
        for cd in chunk:
            lab = run_dir / f"lab_{cd}.mp4"
            if ev.label_clip(run_dir / f"{cd}.mp4", lab, cd):
                parts.append(lab)
        name = f"validate_{run_id}_{k // PER_VIDEO + 1}.mp4"
        if parts and ev.concat(parts, ev.SCRATCH / name):
            ev.say(f"video {k // PER_VIDEO + 1}: {ev.LINK_BASE}/{name}\n   ordine: {' '.join(chunk)}")
    ev.say(f"RUN {run_id} done. Label the codes (bad / part / ok), THEN: python3 exp_validate.py reveal {run_id}")
    return 0


def _rows(run_id):
    return json.loads((ef.OUT / f"validate_{run_id}.json").read_text())


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "reveal":
        for r in _rows(sys.argv[2]):
            g = r.get("geo") or {}
            print(r["code"], r["case"], r["cat"], r.get("standard"), f"new_max={g.get('new_max')}", (r.get("judge") or {}).get("verdict"), "; ".join(r.get("reasons") or []))
        sys.exit(0)
    if len(sys.argv) >= 4 and sys.argv[1] == "score":
        d = json.loads(Path(sys.argv[3]).read_text())
        print(json.dumps(score(_rows(sys.argv[2]), {c: k for k in ("bad", "part", "ok") for c in d.get(k, [])}), indent=1))
        sys.exit(0)
    if len(sys.argv) < 2 or sys.argv[1] != "run":
        print(__doc__); sys.exit(1)
    sys.exit(main(sys.argv[2:]))
